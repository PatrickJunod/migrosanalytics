<script>
import { ref, computed, onMounted, onUnmounted, nextTick, watch } from 'vue';
import { Chart, registerables } from 'chart.js';

// Composables
import { useTransactions } from './composables/useTransactions';
import { useFilters } from './composables/useFilters';
import { useStats } from './composables/useStats';
import { useCharts } from './composables/useCharts';

// Components
import FileUpload from './components/common/FileUpload.vue';
import LoadedFiles from './components/common/LoadedFiles.vue';
import FilterSection from './components/FilterSection.vue';
import TabNavigation from './components/common/TabNavigation.vue';
import OverviewTab from './components/tabs/OverviewTab.vue';
import TrendsTab from './components/tabs/TrendsTab.vue';
import ProductsTab from './components/tabs/ProductsTab.vue';
import StoresTab from './components/tabs/StoresTab.vue';

// Utils
import { formatCurrency, formatDate } from './utils/formatters';
import { ITEMS_PER_PAGE } from './utils/constants';

Chart.register(...registerables);

export default {
  name: 'App',
  components: {
    FileUpload,
    LoadedFiles,
    FilterSection,
    TabNavigation,
    OverviewTab,
    TrendsTab,
    ProductsTab,
    StoresTab
  },
  setup() {
    // Composables
    const { purchases, loadedFiles, isLoading, processFiles, removeFile } = useTransactions();
    const { filters, availableCategories, availableShops, dateRange, filteredPurchases, updateFilters } = useFilters(purchases);
    const { stats, topProducts, topExpensiveProducts, storeStats } = useStats(filteredPurchases);
    const chartComposable = useCharts(filteredPurchases);

    // State
    const isDragging = ref(false);
    const activeTab = ref('overview');
    const searchQuery = ref('');
    const sortBy = ref('date');
    const sortDirection = ref('desc');
    const currentPage = ref(1);
    const timeAggregation = ref('day');
    const additionalFileInput = ref(null);

    // Canvas refs (will be set by components)
    const monthlyChart = ref(null);
    const categoryChart = ref(null);
    const timelineChart = ref(null);
    const dayOfWeekChart = ref(null);
    const hourChart = ref(null);
    const storeChart = ref(null);

    // Chart recreation timeout ref (for debouncing)
    let recreationTimeout = null;

    // Computed
    const hasData = computed(() => purchases.value.length > 0);

    const tabs = [
      { id: 'overview', label: 'Overview' },
      { id: 'trends', label: 'Trends' },
      { id: 'products', label: 'Products' },
      { id: 'stores', label: 'Stores' }
    ];

    // Product table logic
    const filteredPurchasesWithSearch = computed(() => {
      if (filteredPurchases.value.length === 0) return [];

      let filtered = filteredPurchases.value;

      if (searchQuery.value) {
        const query = searchQuery.value.toLowerCase();
        filtered = filtered.filter(p =>
          p.product.toLowerCase().includes(query) ||
          p.store.toLowerCase().includes(query)
        );
      }

      const sorted = [...filtered];
      const direction = sortDirection.value === 'asc' ? 1 : -1;

      switch (sortBy.value) {
        case 'price':
          sorted.sort((a, b) => (a.price - b.price) * direction);
          break;
        case 'quantity':
          sorted.sort((a, b) => (a.quantity - b.quantity) * direction);
          break;
        case 'name':
          sorted.sort((a, b) => a.product.localeCompare(b.product) * direction);
          break;
        default: // date
          sorted.sort((a, b) => (new Date(a.date) - new Date(b.date)) * direction);
      }

      return sorted;
    });

    const paginatedPurchases = computed(() => {
      const start = (currentPage.value - 1) * ITEMS_PER_PAGE;
      const end = start + ITEMS_PER_PAGE;
      return filteredPurchasesWithSearch.value.slice(start, end);
    });

    const totalPages = computed(() => {
      return Math.ceil(filteredPurchasesWithSearch.value.length / ITEMS_PER_PAGE);
    });

    const visiblePages = computed(() => {
      const pages = [];
      const total = totalPages.value;
      const current = currentPage.value;

      if (total <= 7) {
        for (let i = 1; i <= total; i++) pages.push(i);
      } else {
        if (current <= 4) {
          for (let i = 1; i <= 5; i++) pages.push(i);
          pages.push('...');
          pages.push(total);
        } else if (current >= total - 3) {
          pages.push(1);
          pages.push('...');
          for (let i = total - 4; i <= total; i++) pages.push(i);
        } else {
          pages.push(1);
          pages.push('...');
          for (let i = current - 1; i <= current + 1; i++) pages.push(i);
          pages.push('...');
          pages.push(total);
        }
      }

      return pages;
    });

    // Methods
    function handleFilesSelected(files) {
      processFiles(files);
    }

    function handleDragOver() {
      isDragging.value = true;
    }

    function handleDragLeave() {
      isDragging.value = false;
    }

    function handleDrop(e) {
      isDragging.value = false;
      const files = e.dataTransfer.files;
      processFiles(files);
    }

    function triggerAdditionalFileInput() {
      additionalFileInput.value.click();
    }

    function handleAdditionalFiles(e) {
      const files = e.target.files;
      processFiles(files);
    }

    function handleRemoveFile(fileName) {
      removeFile(fileName);
    }

    function handleFilterUpdate(newFilters) {
      updateFilters(newFilters);
    }

    function switchTab(tab) {
      activeTab.value = tab;
      window.location.hash = `#${tab}`;

      nextTick(() => {
        const targetElement = document.getElementById(`${tab}-content`);
        if (targetElement) {
          targetElement.scrollIntoView({ behavior: 'smooth', block: 'start' });
        }
      });
    }

    function handleHashChange() {
      const hash = window.location.hash.substring(1);
      if (['overview', 'trends', 'products', 'stores'].includes(hash)) {
        activeTab.value = hash;
      }
    }

    function toggleSort(column) {
      if (sortBy.value === column) {
        sortDirection.value = sortDirection.value === 'asc' ? 'desc' : 'asc';
      } else {
        sortBy.value = column;
        sortDirection.value = 'desc';
      }
      currentPage.value = 1;
    }

    function handleTimeAggregationChange(value) {
      timeAggregation.value = value;
    }

    // Canvas ready handlers - ONLY store refs, chart creation handled by recreateAllCharts
    function handleMonthlyCanvasReady(canvas) {
      monthlyChart.value = canvas;
    }

    function handleCategoryCanvasReady(canvas) {
      categoryChart.value = canvas;
    }

    function handleTimelineCanvasReady(canvas) {
      timelineChart.value = canvas;
    }

    function handleDayOfWeekCanvasReady(canvas) {
      dayOfWeekChart.value = canvas;
    }

    function handleHourCanvasReady(canvas) {
      hourChart.value = canvas;
    }

    function handleStoreCanvasReady(canvas) {
      storeChart.value = canvas;
    }

    function recreateAllCharts() {
      // Cancel any pending recreation
      if (recreationTimeout) {
        clearTimeout(recreationTimeout);
        recreationTimeout = null;
      }

      // Destroy existing charts immediately and synchronously
      chartComposable.destroyAllCharts();

      // Don't recreate if no data
      if (filteredPurchases.value.length === 0) {
        return;
      }

      // Debounce recreation to avoid conflicts during rapid filter changes
      recreationTimeout = setTimeout(() => {
        nextTick(() => {
          // Verify data still exists after debounce delay
          if (filteredPurchases.value.length === 0) {
            recreationTimeout = null;
            return;
          }

          // Create new charts, checking that canvas elements are still valid and in DOM
          if (monthlyChart.value && monthlyChart.value.isConnected) {
            chartComposable.createMonthlyChart(monthlyChart.value);
          }
          if (categoryChart.value && categoryChart.value.isConnected) {
            chartComposable.createCategoryChart(categoryChart.value);
          }
          if (timelineChart.value && timelineChart.value.isConnected) {
            chartComposable.createTimelineChart(timelineChart.value, timeAggregation.value);
          }
          if (dayOfWeekChart.value && dayOfWeekChart.value.isConnected) {
            chartComposable.createDayOfWeekChart(dayOfWeekChart.value);
          }
          if (hourChart.value && hourChart.value.isConnected) {
            chartComposable.createHourChart(hourChart.value);
          }
          if (storeChart.value && storeChart.value.isConnected) {
            chartComposable.createStoreChart(storeChart.value);
          }
          recreationTimeout = null;
        });
      }, 250);
    }

    // Watchers
    watch([searchQuery, sortBy, sortDirection], () => {
      currentPage.value = 1;
    });

    watch(filters, () => {
      // Recreate charts (handles destruction and debouncing internally)
      recreateAllCharts();
    }, { deep: true });

    watch(timeAggregation, () => {
      if (filteredPurchases.value.length > 0 && timelineChart.value && timelineChart.value.isConnected) {
        nextTick(() => {
          setTimeout(() => {
            // Recreate the timeline chart with new aggregation (createTimelineChart handles destruction)
            chartComposable.createTimelineChart(timelineChart.value, timeAggregation.value);
          }, 50);
        });
      }
    });

    // Watch for data being loaded
    watch(isLoading, (newVal, oldVal) => {
      if (oldVal && !newVal && filteredPurchases.value.length > 0) {
        // Data just finished loading, create all charts
        nextTick(() => {
          setTimeout(() => {
            recreateAllCharts();
          }, 100);
        });
      }
    });

    // Watch for purchases changes (initial load)
    watch(purchases, (newVal) => {
      if (newVal.length > 0 && !isLoading.value) {
        nextTick(() => {
          setTimeout(() => {
            recreateAllCharts();
          }, 100);
        });
      }
    });

    // Lifecycle
    onMounted(() => {
      handleHashChange();
      window.addEventListener('hashchange', handleHashChange);
    });

    onUnmounted(() => {
      // Cancel any pending chart recreation
      if (recreationTimeout) {
        clearTimeout(recreationTimeout);
      }
      // Destroy all charts
      chartComposable.destroyAllCharts();
      // Remove event listener
      window.removeEventListener('hashchange', handleHashChange);
    });

    return {
      // State
      isDragging,
      activeTab,
      searchQuery,
      sortBy,
      sortDirection,
